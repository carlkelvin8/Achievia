/// Case- and accent-insensitive match used by the picker's search box.
bool schoolMatches(String school, String query) {
  String fold(String value) => value
      .toLowerCase()
      .replaceAll('ñ', 'n')
      .replaceAll('–', '-')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
  final q = fold(query);
  return q.isEmpty || fold(school).contains(q);
}

