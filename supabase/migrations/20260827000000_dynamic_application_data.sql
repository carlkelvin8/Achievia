create table if not exists public.goals (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_date date not null,
  title text not null,
  details text not null default '',
  is_checked boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, goal_date)
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  notification_type text not null default 'general',
  image_url text,
  data jsonb,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.supplemental_items (
  id bigint generated by default as identity primary key,
  course_id integer,
  kind text not null check (kind in ('mnemonic', 'abbreviation', 'procedure')),
  title text not null,
  content text not null default '',
  image_url text,
  file_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.qotd_answers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id integer not null references public.questions(id) on delete cascade,
  quiz_id integer not null references public.quizzes(id) on delete cascade,
  choice_id integer not null references public.choices(id) on delete cascade,
  is_correct boolean not null,
  answered_at timestamptz not null default now()
);

create table if not exists public.study_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  duration_minutes integer not null check (duration_minutes > 0),
  session_type text not null default 'pomodoro',
  created_at timestamptz not null default now(),
  check (ended_at > started_at)
);

create table if not exists public.authors (
  id bigint generated by default as identity primary key,
  name text not null,
  university text not null default '',
  achievement text not null default '',
  greeting text not null default '',
  message text not null default '',
  image_url text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

