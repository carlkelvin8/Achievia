create extension if not exists "pgcrypto";

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  quiz_id integer not null,
  student_id uuid not null references auth.users(id) on delete cascade,
  score numeric not null default 0,
  attempted_at timestamptz not null default now(),
  answer jsonb not null default '[]'::jsonb,
  no_of_attempt integer not null default 1,
  summary jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

do $$
declare
  current_student_id_type text;
begin
  select data_type
  into current_student_id_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'quiz_attempts'
    and column_name = 'student_id';

  if current_student_id_type is distinct from 'uuid' then
    if current_student_id_type is not null
      and not exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'quiz_attempts'
          and column_name = 'student_id_legacy'
      )
    then
      alter table public.quiz_attempts
        rename column student_id to student_id_legacy;

      alter table public.quiz_attempts
        alter column student_id_legacy drop not null;
    end if;

    if not exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'quiz_attempts'
        and column_name = 'student_id'
    ) then
      alter table public.quiz_attempts
        add column student_id uuid references auth.users(id) on delete cascade;
    end if;
  end if;
end;
$$;

alter table public.quiz_attempts
  alter column answer type jsonb using coalesce(to_jsonb(answer), '[]'::jsonb),
  alter column answer set default '[]'::jsonb,
  alter column summary type jsonb using coalesce(to_jsonb(summary), '[]'::jsonb),
  alter column summary set default '[]'::jsonb;

create index if not exists quiz_attempts_student_id_idx
  on public.quiz_attempts(student_id);

create index if not exists quiz_attempts_student_attempt_idx
  on public.quiz_attempts(student_id, no_of_attempt);

alter table public.quiz_attempts enable row level security;

drop policy if exists "Users can read their own quiz attempts" on public.quiz_attempts;
drop policy if exists "Users can insert their own quiz attempts" on public.quiz_attempts;
drop policy if exists "Users can update their own quiz attempts" on public.quiz_attempts;
drop policy if exists "Users can delete their own quiz attempts" on public.quiz_attempts;

create policy "Users can read their own quiz attempts"
  on public.quiz_attempts
  for select
  to authenticated
  using ((select auth.uid()) = student_id);

create policy "Users can insert their own quiz attempts"
  on public.quiz_attempts
  for insert
  to authenticated
  with check ((select auth.uid()) = student_id);

create policy "Users can update their own quiz attempts"
  on public.quiz_attempts
  for update
  to authenticated
  using ((select auth.uid()) = student_id)
  with check ((select auth.uid()) = student_id);

create policy "Users can delete their own quiz attempts"
  on public.quiz_attempts
  for delete
  to authenticated
  using ((select auth.uid()) = student_id);
