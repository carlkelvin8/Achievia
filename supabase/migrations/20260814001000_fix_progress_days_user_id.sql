create table if not exists public.progress_days (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  activity_date date not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

do $$
declare
  current_user_id_type text;
begin
  select data_type
  into current_user_id_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'progress_days'
    and column_name = 'user_id';

  if current_user_id_type is distinct from 'uuid' then
    if current_user_id_type is not null
      and not exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'progress_days'
          and column_name = 'user_id_legacy'
      )
    then
      alter table public.progress_days
        rename column user_id to user_id_legacy;

      alter table public.progress_days
        alter column user_id_legacy drop not null;
    end if;

    if not exists (
      select 1
      from information_schema.columns
      where table_schema = 'public'
        and table_name = 'progress_days'
        and column_name = 'user_id'
    ) then
      alter table public.progress_days
        add column user_id uuid references auth.users(id) on delete cascade;
    end if;
  end if;
end;
$$;

create unique index if not exists progress_days_user_activity_idx
  on public.progress_days(user_id, activity_date);

alter table public.progress_days enable row level security;

do $$
declare
  policy_record record;
begin
  for policy_record in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'progress_days'
  loop
    execute format(
      'drop policy if exists %I on public.progress_days',
      policy_record.policyname
    );
  end loop;
end;
$$;

create policy "Users can read their own progress days"
  on public.progress_days
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can insert their own progress days"
  on public.progress_days
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own progress days"
  on public.progress_days
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

notify pgrst, 'reload schema';
