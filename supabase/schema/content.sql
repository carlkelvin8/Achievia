-- Application-derived schema for EMPTY installations only. Not a hosted dump.
-- Existing deployments must compare catalog evidence before adopting this DDL.
create table public.subjects (
  id integer generated by default as identity primary key,
  title text not null, course_id integer, description text, image text,
  day_subject text, created_at timestamptz not null default now()
);
create table public.quizzes (
  id integer generated by default as identity primary key,
  subject_id integer references public.subjects(id),
  title text not null, description text,
  configured_question_count integer check (configured_question_count >= 0),
  created_at timestamptz not null default now()
);
create table public.questions (
  id integer generated by default as identity primary key,
  quiz_id integer not null references public.quizzes(id),
  question_text text not null
);
create table public.choices (
  id integer generated by default as identity primary key,
  question_id integer not null references public.questions(id),
  choice_text text not null, is_correct boolean not null default false
);
-- Enum name/complete vocabulary on the hosted project are unknown. These are
-- the labels consumed by the current published_modules view, plus draft.
create type public.module_status as enum ('draft', 'published', 'active');
create table public.modules (
  id integer generated by default as identity primary key,
  title text not null, description text,
  user_id uuid references public.profiles(id),
  created_at timestamptz not null default now(), file text, image text,
  status public.module_status not null default 'draft',
  subject_id integer references public.subjects(id)
);
create table public.mnemonics (
  id integer generated by default as identity primary key,
  subject_id integer references public.subjects(id),
  title text, file_path text, description text, deleted_at timestamptz
);
create table public.abbreviations (
  id integer generated by default as identity primary key,
  subject_id integer references public.subjects(id),
  short_form text, full_form text, deleted_at timestamptz
);
create table public.procedures (
  id integer generated by default as identity primary key,
  subject_id integer references public.subjects(id),
  title text, file_path text, deleted_at timestamptz
);
-- RLS is required for each API relation. Content writes remain server-managed.
do $$ declare t text; begin
  foreach t in array array['subjects','quizzes','questions','choices',
    'mnemonics','abbreviations','procedures'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('create policy "Application content read" on public.%I for select to authenticated using (%s)',
      t, case when t in ('mnemonics','abbreviations','procedures')
        then 'deleted_at is null' else 'true' end);
  end loop;
end $$;
alter table public.modules enable row level security;
