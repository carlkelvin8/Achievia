"""Build a separate EMPTY-database installation, never rewrite migration history.

Usage: python scripts/build_database_baseline.py
Output: build/database/achievia_baseline.sql (review before use).
No database connection or hosted project configuration is accepted.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'supabase/schema/baseline_manifest.json'


def normalized(path):
    return path.read_text(encoding='utf-8').replace('\r\n', '\n')


def build():
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    actual_files = {p.name for p in (ROOT / 'supabase/migrations').glob('*.sql')}
    expected_files = {item['file'] for item in manifest['history']}
    if actual_files != expected_files:
        raise ValueError('Migration inventory changed; review and update the baseline manifest')
    for item in manifest['history']:
        source = normalized(ROOT / 'supabase/migrations' / item['file'])
        if hashlib.sha256(source.encode()).hexdigest() != item['sha256_lf']:
            raise ValueError('Historical source changed: ' + item['file'])
    parts = ["""-- Generated by scripts/build_database_baseline.py. EMPTY DATABASES ONLY.
-- Supabase must already provide auth.users, auth.uid(), anon/authenticated.
begin;
set local lock_timeout = '5s';
do $$ begin
  if current_setting('server_version_num')::integer < 150000 then
    raise exception 'PostgreSQL 15+ required for security_invoker views';
  end if;
  if exists (select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relkind in ('r','p','v','m','S','f'))
    or exists (select 1 from auth.users) then
    raise exception 'Baseline refuses non-empty application/auth schema';
  end if;
end $$;
"""]
    for entry in manifest['install']:
        source = normalized(ROOT / entry['path'])
        if entry.get('transform') == 'tasks_uuid_only':
            # Exact reviewed extraction; retain policies/indexes, omit DROP and
            # the contradictory second CREATE. Fail if the source shape changes.
            start = source.index('create table public.tasks (')
            end = source.index('create table if not exists public.tasks (')
            tail = source.index('create index if not exists tasks_user_deadline_idx')
            source = source[start:end] + source[tail:]
        # Existing sources own transactions; the compiled baseline owns ONE.
        source = re.sub(r'(?im)^\s*(begin|commit);\s*$', '', source)
        parts.append('\n-- SOURCE: ' + entry['path'] + '\n' + source)
    parts.append('\ncommit;\n')
    return '\n'.join(parts)


if __name__ == '__main__':
    output = ROOT / 'build/database/achievia_baseline.sql'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build(), encoding='utf-8', newline='\n')
    print(output)
